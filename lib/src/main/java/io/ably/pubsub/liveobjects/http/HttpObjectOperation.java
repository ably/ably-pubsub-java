package io.ably.pubsub.liveobjects.http;

import io.ably.pubsub.liveobjects.message.ObjectsMapSemantics;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * An operation published with {@link io.ably.pubsub.liveobjects.HttpObject#publish}.
 *
 * <p>Each operation carries exactly one operation body. Create an operation with one of the static
 * factories, which fixes the body, then set the optional common fields with {@link #withObjectId},
 * {@link #withPath} and {@link #withId}. Instances are immutable; the {@code with*} methods return
 * a copy.
 *
 * <pre>{@code
 * HttpObjectOperation.mapSet("name", PublishObjectData.string("Alice")).withPath("profile");
 * HttpObjectOperation.counterInc(1).withObjectId("counter:abc@1700000000000");
 * }</pre>
 *
 * <p>Which target fields an operation needs depends on its type (see the factories). The library
 * does not check targeting; the server rejects an invalid combination (RSO3g).
 *
 * <p>Spec: RSO5
 */
public final class HttpObjectOperation {

    private final @Nullable String id;
    private final @Nullable String objectId;
    private final @Nullable String path;
    private final @Nullable MapCreate mapCreate;
    private final @Nullable CreateWithObjectId mapCreateWithObjectId;
    private final @Nullable MapSet mapSet;
    private final @Nullable MapRemove mapRemove;
    private final @Nullable CounterCreate counterCreate;
    private final @Nullable CreateWithObjectId counterCreateWithObjectId;
    private final @Nullable CounterInc counterInc;

    private HttpObjectOperation(@Nullable String id, @Nullable String objectId, @Nullable String path,
                                @Nullable MapCreate mapCreate, @Nullable CreateWithObjectId mapCreateWithObjectId,
                                @Nullable MapSet mapSet, @Nullable MapRemove mapRemove,
                                @Nullable CounterCreate counterCreate, @Nullable CreateWithObjectId counterCreateWithObjectId,
                                @Nullable CounterInc counterInc) {
        this.id = id;
        this.objectId = objectId;
        this.path = path;
        this.mapCreate = mapCreate;
        this.mapCreateWithObjectId = mapCreateWithObjectId;
        this.mapSet = mapSet;
        this.mapRemove = mapRemove;
        this.counterCreate = counterCreate;
        this.counterCreateWithObjectId = counterCreateWithObjectId;
        this.counterInc = counterInc;
    }

    //region Factories

    /**
     * Creates a new map. Without a target, the map is standalone and its ID is returned in
     * {@link HttpObjectPublishResult#getObjectIds()}; with {@link #withPath}, it's assigned at that path.
     * <p>Spec: RSO5c
     *
     * @param semantics the conflict-resolution semantics.
     * @param entries the initial entries, by key.
     */
    public static @NotNull HttpObjectOperation mapCreate(@NotNull ObjectsMapSemantics semantics,
                                                         @NotNull Map<String, PublishObjectData> entries) {
        return mapCreate(new MapCreate(semantics, entries));
    }

    /**
     * Creates a new map with {@link ObjectsMapSemantics#LWW} semantics; see
     * {@link #mapCreate(ObjectsMapSemantics, Map)}.
     */
    public static @NotNull HttpObjectOperation mapCreate(@NotNull Map<String, PublishObjectData> entries) {
        return mapCreate(ObjectsMapSemantics.LWW, entries);
    }

    /** Spec: RSO5c */
    public static @NotNull HttpObjectOperation mapCreate(@NotNull MapCreate body) {
        return new HttpObjectOperation(null, null, null, body, null, null, null, null, null, null);
    }

    /**
     * Creates a new map with an ID generated by
     * {@link io.ably.pubsub.liveobjects.HttpObject#generateObjectId}, setting the object ID, initial
     * value and nonce from the result.
     * <p>Spec: RSO5d
     */
    public static @NotNull HttpObjectOperation mapCreateWithObjectId(@NotNull HttpObjectGenerateIdResult generated) {
        return mapCreateWithObjectId(generated.getObjectId(), generated.getInitialValue(), generated.getNonce());
    }

    /**
     * Creates a new map with a client-generated ID. All three values must come unchanged from the
     * same {@link io.ably.pubsub.liveobjects.HttpObject#generateObjectId} result.
     * <p>Spec: RSO5d
     */
    public static @NotNull HttpObjectOperation mapCreateWithObjectId(@NotNull String objectId,
                                                                     @NotNull String initialValue,
                                                                     @NotNull String nonce) {
        return new HttpObjectOperation(null, objectId, null, null,
            new CreateWithObjectId(initialValue, nonce), null, null, null, null, null);
    }

    /**
     * Sets a key in an existing map, targeted by {@link #withObjectId} or {@link #withPath}.
     * <p>Spec: RSO5e
     */
    public static @NotNull HttpObjectOperation mapSet(@NotNull String key, @NotNull PublishObjectData value) {
        return new HttpObjectOperation(null, null, null, null, null, new MapSet(key, value), null, null, null, null);
    }

    /**
     * Removes a key from an existing map, targeted by {@link #withObjectId} or {@link #withPath}.
     * <p>Spec: RSO5f
     */
    public static @NotNull HttpObjectOperation mapRemove(@NotNull String key) {
        return new HttpObjectOperation(null, null, null, null, null, null, new MapRemove(key), null, null, null);
    }

    /**
     * Creates a new counter. Targeting works as for {@link #mapCreate(ObjectsMapSemantics, Map)}.
     * <p>Spec: RSO5g
     */
    public static @NotNull HttpObjectOperation counterCreate(@NotNull Number count) {
        return counterCreate(new CounterCreate(count));
    }

    /** Spec: RSO5g */
    public static @NotNull HttpObjectOperation counterCreate(@NotNull CounterCreate body) {
        return new HttpObjectOperation(null, null, null, null, null, null, null, body, null, null);
    }

    /**
     * Creates a new counter with an ID generated by
     * {@link io.ably.pubsub.liveobjects.HttpObject#generateObjectId}.
     * <p>Spec: RSO5h
     */
    public static @NotNull HttpObjectOperation counterCreateWithObjectId(@NotNull HttpObjectGenerateIdResult generated) {
        return counterCreateWithObjectId(generated.getObjectId(), generated.getInitialValue(), generated.getNonce());
    }

    /**
     * Creates a new counter with a client-generated ID; see
     * {@link #mapCreateWithObjectId(String, String, String)}.
     * <p>Spec: RSO5h
     */
    public static @NotNull HttpObjectOperation counterCreateWithObjectId(@NotNull String objectId,
                                                                         @NotNull String initialValue,
                                                                         @NotNull String nonce) {
        return new HttpObjectOperation(null, objectId, null, null, null, null, null, null,
            new CreateWithObjectId(initialValue, nonce), null);
    }

    /**
     * Adds {@code number} to an existing counter (negative to decrement), targeted by
     * {@link #withObjectId} or {@link #withPath}.
     * <p>Spec: RSO5i
     */
    public static @NotNull HttpObjectOperation counterInc(@NotNull Number number) {
        return new HttpObjectOperation(null, null, null, null, null, null, null, null, null, new CounterInc(number));
    }

    //endregion

    //region Common fields

    /**
     * Returns a copy with the operation ID set, used for idempotent publishing. The library never
     * generates one.
     * <p>Spec: RSO5a1, RSO3f
     */
    public @NotNull HttpObjectOperation withId(@Nullable String id) {
        return new HttpObjectOperation(id, objectId, path, mapCreate, mapCreateWithObjectId, mapSet, mapRemove,
            counterCreate, counterCreateWithObjectId, counterInc);
    }

    /**
     * Returns a copy that targets the object with this ID.
     * <p>Spec: RSO5a2
     */
    public @NotNull HttpObjectOperation withObjectId(@Nullable String objectId) {
        return new HttpObjectOperation(id, objectId, path, mapCreate, mapCreateWithObjectId, mapSet, mapRemove,
            counterCreate, counterCreateWithObjectId, counterInc);
    }

    /**
     * Returns a copy that targets the object(s) at this path in the channel object. The path is sent
     * as given.
     * <p>Spec: RSO5a3, RSO6
     */
    public @NotNull HttpObjectOperation withPath(@Nullable String path) {
        return new HttpObjectOperation(id, objectId, path, mapCreate, mapCreateWithObjectId, mapSet, mapRemove,
            counterCreate, counterCreateWithObjectId, counterInc);
    }

    //endregion

    //region Getters

    public @Nullable String getId() {
        return id;
    }

    public @Nullable String getObjectId() {
        return objectId;
    }

    public @Nullable String getPath() {
        return path;
    }

    public @Nullable MapCreate getMapCreate() {
        return mapCreate;
    }

    public @Nullable CreateWithObjectId getMapCreateWithObjectId() {
        return mapCreateWithObjectId;
    }

    public @Nullable MapSet getMapSet() {
        return mapSet;
    }

    public @Nullable MapRemove getMapRemove() {
        return mapRemove;
    }

    public @Nullable CounterCreate getCounterCreate() {
        return counterCreate;
    }

    public @Nullable CreateWithObjectId getCounterCreateWithObjectId() {
        return counterCreateWithObjectId;
    }

    public @Nullable CounterInc getCounterInc() {
        return counterInc;
    }

    //endregion

    //region Operation bodies

    /**
     * The body of a {@code mapCreate} operation, also accepted by
     * {@link HttpObjectGenerateIdBody#mapCreate(MapCreate)}.
     * <p>Spec: RSO5c
     */
    public static final class MapCreate {
        private final @NotNull ObjectsMapSemantics semantics;
        private final @NotNull Map<String, PublishObjectData> entries;

        /**
         * @param semantics the conflict-resolution semantics (RSO5c1).
         * @param entries the initial entries, by key (RSO5c2). Iteration order is kept on the wire.
         */
        public MapCreate(@NotNull ObjectsMapSemantics semantics, @NotNull Map<String, PublishObjectData> entries) {
            this.semantics = semantics;
            this.entries = Collections.unmodifiableMap(new LinkedHashMap<>(entries));
        }

        public @NotNull ObjectsMapSemantics getSemantics() {
            return semantics;
        }

        public @NotNull Map<String, PublishObjectData> getEntries() {
            return entries;
        }
    }

    /**
     * The body of a {@code mapCreateWithObjectId} or {@code counterCreateWithObjectId} operation.
     * <p>Spec: RSO5d, RSO5h
     */
    public static final class CreateWithObjectId {
        private final @NotNull String initialValue;
        private final @NotNull String nonce;

        public CreateWithObjectId(@NotNull String initialValue, @NotNull String nonce) {
            this.initialValue = initialValue;
            this.nonce = nonce;
        }

        /** Spec: RSO5d1 */
        public @NotNull String getInitialValue() {
            return initialValue;
        }

        /** Spec: RSO5d2 */
        public @NotNull String getNonce() {
            return nonce;
        }
    }

    /** Spec: RSO5e */
    public static final class MapSet {
        private final @NotNull String key;
        private final @NotNull PublishObjectData value;

        public MapSet(@NotNull String key, @NotNull PublishObjectData value) {
            this.key = key;
            this.value = value;
        }

        public @NotNull String getKey() {
            return key;
        }

        public @NotNull PublishObjectData getValue() {
            return value;
        }
    }

    /** Spec: RSO5f */
    public static final class MapRemove {
        private final @NotNull String key;

        public MapRemove(@NotNull String key) {
            this.key = key;
        }

        public @NotNull String getKey() {
            return key;
        }
    }

    /**
     * The body of a {@code counterCreate} operation, also accepted by
     * {@link HttpObjectGenerateIdBody#counterCreate(CounterCreate)}.
     * <p>Spec: RSO5g
     */
    public static final class CounterCreate {
        private final @NotNull Number count;

        public CounterCreate(@NotNull Number count) {
            this.count = count;
        }

        public @NotNull Number getCount() {
            return count;
        }
    }

    /** Spec: RSO5i */
    public static final class CounterInc {
        private final @NotNull Number number;

        public CounterInc(@NotNull Number number) {
            this.number = number;
        }

        public @NotNull Number getNumber() {
            return number;
        }
    }

    //endregion
}
